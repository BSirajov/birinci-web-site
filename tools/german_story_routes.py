"""Use category anchors for German stories; retain old URLs with HTTP 301s."""
from pathlib import Path
import json
import posixpath
import re
from urllib.parse import urlsplit, urlunsplit


def migrate(root: Path) -> list[str]:
    root = root.resolve()
    catalog_path = root / 'de/assets/stories-data.js'
    raw = catalog_path.read_text(encoding='utf-8')
    catalog = json.loads(raw.split('=', 1)[1].strip().rstrip(';'))
    routes = {s['stem']: f"de/categories/{c['slug']}.html#{s['stem']}"
              for c in catalog['categories'] for s in c['stories']}
    for target in routes.values():
        dest, anchor = target.split('#')
        if f'id="{anchor}"' not in (root / dest).read_text(encoding='utf-8'):
            raise ValueError(f'Missing redirect target: {target}')
    changed = []

    def write(p, text):
        if not p.exists() or p.read_text(encoding='utf-8') != text:
            p.write_text(text, encoding='utf-8', newline='\n')
            changed.append(p.relative_to(root).as_posix())

    def replace_url(url, page):
        u = urlsplit(url)
        if u.netloc and u.netloc not in ('birinci.cloud', 'www.birinci.cloud'):
            return url
        resolved = u.path.lstrip('/') if u.path.startswith('/') else posixpath.normpath(posixpath.join(posixpath.dirname(page), u.path))
        stem = posixpath.basename(resolved).removesuffix('.html')
        if resolved != f'de/stories/{stem}.html' or stem not in routes:
            return url
        target, anchor = routes[stem].split('#')
        path = '/' + target if u.path.startswith('/') or u.netloc else posixpath.relpath(target, posixpath.dirname(page))
        return urlunsplit((u.scheme, u.netloc, path, u.query, anchor))

    for p in (root / 'de').rglob('*.html'):
        rel = p.relative_to(root).as_posix()
        if any(x in p.parts for x in ('_backups', '_reviews', 'wisdom-stories')):
            continue
        if rel == f'de/stories/{p.stem}.html' and p.stem in routes:
            continue
        text = p.read_text(encoding='utf-8')
        text = re.sub(r'href="([^"]+)"', lambda m: 'href="' + replace_url(m[1], rel) + '"', text)
        write(p, text)
    for name in ('stories-data.js', 'search-index.js'):
        p = root / 'de/assets' / name
        text = p.read_text(encoding='utf-8')
        text = re.sub(r'"href":"stories/([^"/]+)\.html"',
                      lambda m: '"href":"' + routes[m[1]].removeprefix('de/') + '"', text)
        write(p, text)
    rules = ['# Generated by tools/german_story_routes.py; legacy story bookmarks.',
             'RewriteEngine On']
    for stem, target in sorted(routes.items()):
        rules.append(f'RewriteRule ^{re.escape(stem)}\\.html$ /{target} [R=301,L,NE]')
    write(root / 'de/stories/.htaccess', '\n'.join(rules) + '\n')
    sitemap = root / 'sitemap.xml'
    if sitemap.exists():
        text = sitemap.read_text(encoding='utf-8')
        text = re.sub(r'\s*<url>\s*<loc>https://birinci\.cloud/de/stories/[^<]+\.html</loc>.*?</url>', '', text, flags=re.S)
        write(sitemap, text)
    # Only remove generated pages with an explicit, validated destination.
    for stem, target in routes.items():
        p = root / 'de/stories' / (stem + '.html')
        if p.is_file():
            p.unlink()
            changed.append(p.relative_to(root).as_posix())
    return changed


if __name__ == '__main__':
    print('\n'.join(migrate(Path(__file__).resolve().parents[1])))
